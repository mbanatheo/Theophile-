create table if not exists public.classes (
  id bigint generated by default as identity primary key,
  class_name text not null unique,
  description text not null default ''
);

create table if not exists public.students (
  id bigint generated by default as identity primary key,
  student_id text not null unique,
  full_name text not null,
  gender text not null default '',
  class_id bigint references public.classes(id),
  phone text not null default '',
  email text not null default '',
  registration_date date not null default current_date,
  active_status boolean not null default true
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id text not null references public.students(student_id) on delete restrict,
  attendance_date date not null default current_date,
  attendance_time time not null default current_time,
  status text not null default 'present',
  session_id text not null default 'default',
  device_id text not null default 'esp32-main',
  created_at timestamptz not null default now(),
  unique (student_id, attendance_date, session_id)
);

alter table public.classes enable row level security;
alter table public.students enable row level security;
alter table public.attendance enable row level security;

grant usage, select on all sequences in schema public to service_role;
grant all on public.classes, public.students, public.attendance to service_role;

