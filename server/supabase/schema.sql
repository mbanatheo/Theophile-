create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text not null,
  category text not null,
  price numeric not null check (price >= 0),
  stock integer not null check (stock >= 0)
);

create unique index if not exists products_sku_case_insensitive_unique
  on public.products (lower(sku));

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null default '',
  phone text not null default ''
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  product_id bigint not null,
  product_name text not null,
  customer_id bigint not null,
  customer_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric not null check (unit_price >= 0),
  total numeric not null check (total >= 0),
  date timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.customers enable row level security;
alter table public.sales enable row level security;

grant select, insert, update, delete on public.products to service_role;
grant select, insert, update, delete on public.customers to service_role;
grant select, insert, update, delete on public.sales to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.record_sale(
  p_product_id bigint,
  p_customer_id bigint,
  p_quantity integer
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_product public.products%rowtype;
  v_customer public.customers%rowtype;
  v_sale public.sales%rowtype;
begin
  if p_quantity < 1 then
    raise exception 'Quantity must be at least one';
  end if;

  select * into v_product
  from public.products
  where id = p_product_id
  for update;

  if not found then
    return jsonb_build_object('error', 'product_not_found');
  end if;

  select * into v_customer
  from public.customers
  where id = p_customer_id;

  if not found then
    return jsonb_build_object('error', 'customer_not_found');
  end if;

  if v_product.stock < p_quantity then
    return jsonb_build_object('error', 'insufficient_stock');
  end if;

  update public.products
  set stock = stock - p_quantity
  where id = p_product_id;

  insert into public.sales (
    product_id,
    product_name,
    customer_id,
    customer_name,
    quantity,
    unit_price,
    total
  )
  values (
    v_product.id,
    v_product.name,
    v_customer.id,
    v_customer.name,
    p_quantity,
    v_product.price,
    v_product.price * p_quantity
  )
  returning * into v_sale;

  return jsonb_build_object(
    'id', v_sale.id,
    'productId', v_sale.product_id,
    'productName', v_sale.product_name,
    'customerId', v_sale.customer_id,
    'customerName', v_sale.customer_name,
    'quantity', v_sale.quantity,
    'unitPrice', v_sale.unit_price,
    'total', v_sale.total,
    'date', v_sale.date
  );
end;
$$;

revoke all on function public.record_sale(bigint, bigint, integer) from public, anon, authenticated;
grant execute on function public.record_sale(bigint, bigint, integer) to service_role;

